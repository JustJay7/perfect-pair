const assert = require('node:assert/strict');
const { once } = require('node:events');
const { chromium } = require('playwright');

(async () => {
  const { BedrockService } = await import('../backend/bedrock.mjs');
  const { createServer } = await import('../backend/server.mjs');
  let decision, deny = false;
  const sent = [];
  const text = value => ({ output: { message: { role: 'assistant', content: [{ text: value }] } }, stopReason: 'end_turn', usage: { outputTokens: 40 } });
  const service = new BedrockService({ clientFactory: () => ({ destroy() {}, async send(command) {
    sent.push(structuredClone(command.input));
    if (deny) throw Object.assign(new Error('Private provider diagnostic'), { name: 'ExpiredTokenException' });
    const last = command.input.messages.at(-1);
    if (!command.input.toolConfig) return text('Hello, Perfect Pair team.');
    if (last.content.some(c => c.toolResult)) return text(JSON.stringify(decision));
    return { output: { message: { role: 'assistant', content: [{ text: 'Checking the order.' }, { toolUse: { toolUseId: 'lookup-1', name: 'look_up_order_and_customer', input: { order_id: 'O-58213', why: 'Verify the order before offering a resolution.' } } }] } }, stopReason: 'tool_use', usage: { outputTokens: 30 } };
  } }) });
  const server = createServer({ service }); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('https://**/*', route => route.abort());
    await page.goto(base);
    await page.waitForFunction(() => STATE.live.checked && WORK.ready);
    await page.locator('#workspace-role').selectOption('customer_service');
    await page.locator('#settings-open').click();
    assert.equal(await page.locator('#mode-live').isDisabled(), true);
    assert.equal(await page.locator('#aws-connect').isVisible(), true);
    assert.match(await page.locator('#livenote').textContent(), /Connect AWS/);
    // A deterministic fixture tests transport and real UI/tools, not live model quality.
    decision = await page.evaluate(async () => { const d = await investigate('maya', { mode: 'scripted' }); await resetAll(); return d; });
    await page.goto(base + '/connect');
    await page.locator('#accessKeyId').fill('temporary-test-access');
    await page.locator('#secretAccessKey').fill('temporary-test-secret');
    await page.locator('#sessionToken').fill('temporary-test-token');
    await page.getByRole('button', { name: 'Connect and test' }).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Connected to Amazon Bedrock'));
    assert.equal(await page.locator('#secretAccessKey').inputValue(), '');
    assert.equal(await page.locator('#sessionToken').inputValue(), '');
    assert.doesNotMatch(await page.evaluate(() => JSON.stringify({local:{...localStorage},session:{...sessionStorage}})), /temporary-test-access|temporary-test-secret|temporary-test-token/);
    await page.goto(base);
    await page.waitForFunction(() => STATE.live.available && WORK.ready);
    assert.equal(await page.evaluate(() => STATE.mode), 'scripted', 'loading the app does not start paid live runs');
    await page.locator('#settings-open').click();
    await page.locator('#mode-live').click();
    assert.match(await page.locator('#livenote').textContent(), /Amazon Bedrock/);
    const callsBeforeReload=sent.length;
    await page.reload();await page.waitForFunction(()=>STATE.live.checked&&WORK.ready);
    assert.equal(await page.evaluate(()=>STATE.mode),'live','Explicit Live choice survives refresh');
    assert.equal(sent.length,callsBeforeReload,'Refresh does not reconnect or call the model');
    await page.locator('#settings-open').click();
    const result = await page.evaluate(async () => {
      const d = await investigate('maya', { mode: 'live', throwOnError: true });
      return { status: CASES.maya.status, tools: CASES.maya.stats.tools, calls: CASES.maya.events.filter(e => e.kind === 'call').map(e => e.tool), model: CASES.maya.tierApplied, decision: d };
    });
    assert.equal(result.status, 'options');
    assert.ok(result.calls.includes('look_up_order_and_customer'));
    assert.equal(result.model, 'us.anthropic.claude-sonnet-5-5');
    assert.ok(sent.at(-1).messages.at(-1).content[0].toolResult.content[0].json.order);
    assert.doesNotMatch(JSON.stringify(sent), /temporary-test-secret|temporary-test-token/);
    await page.getByRole('group', { name: 'Dataset', exact: true }).getByRole('button', { name: 'Actual', exact: true }).click();
    assert.equal(await page.evaluate(() => UI.dataSource), 'actual');
    assert.equal(await page.evaluate(() => CASES.maya.status), 'options');
    await page.locator('#mode-scripted').click();
    assert.equal(await page.evaluate(() => STATE.mode), 'scripted');
    deny = true;
    const failed = await page.evaluate(async () => { await investigate('priya', { mode: 'live' }); return { available: STATE.live.available, mode: STATE.mode, error: CASES.priya.error }; });
    assert.equal(failed.available, false);
    assert.equal(failed.mode, 'scripted');
    assert.match(failed.error.copy, /expired/);
    assert.doesNotMatch(failed.error.copy, /Private provider diagnostic/);
    await page.goto(base + '/connect');
    await page.getByRole('button', { name: 'Disconnect', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('not connected'));
    assert.equal(service.status().connected, false);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= 390));
    if (process.env.PP_SCREENSHOTS) await page.screenshot({ path: process.env.PP_SCREENSHOTS + '/connect-aws.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ liveProvider: 'mock AWS SDK, not real inference', connectionForm: 'passed', returnWorkflow: 'passed', actualToggle: 'passed', expiredCredentials: 'passed', disconnect: 'passed', mobileSetup: 'passed', consoleErrors: errors.length }, null, 2));
  } finally { await browser.close(); server.closeAllConnections(); server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
